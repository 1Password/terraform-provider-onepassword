package provider

import (
	"fmt"
	"strings"
	"testing"

	"github.com/hashicorp/terraform-plugin-testing/helper/resource"
	"github.com/hashicorp/terraform-plugin-testing/knownvalue"
	"github.com/hashicorp/terraform-plugin-testing/plancheck"
	"github.com/hashicorp/terraform-plugin-testing/statecheck"
	"github.com/hashicorp/terraform-plugin-testing/tfjsonpath"

	"github.com/1Password/terraform-provider-onepassword/v3/internal/onepassword/model"
)

// after import, state has no password_recipe. The stored value is kept
// only if the configured recipe could have generated it; a changed recipe regenerates.
// Items that weren't imported regenerate on any recipe change, as before.
func TestAccItemResource_PasswordRecipeAfterImport(t *testing.T) {
	// Stored values look generated by recipe(32): 32 chars with digits and symbols.
	const password = "aB3!cD4@eF5.gH6-iJ7_kL8*mN9!pQ0@"
	const sectionSecret = "Zy1*Xw2_Vu3-Ts4.Rq5@Po6!Nm7*Lk8_"

	loginItem := generateLoginItem()
	loginItem.Fields[1].Value = password

	itemWithSection := generateLoginItem()
	itemWithSection.Sections = []model.ItemSection{{ID: "sec1", Label: "Secrets"}}
	itemWithSection.Fields = append(itemWithSection.Fields, model.ItemField{
		ID:           "secfield1",
		Type:         model.FieldTypeConcealed,
		Label:        "api key",
		Value:        sectionSecret,
		SectionID:    "sec1",
		SectionLabel: "Secrets",
	})

	recipe := func(length int) string {
		return fmt.Sprintf(`
    password_recipe {
      length  = %d
      digits  = true
      symbols = true
    }`, length)
	}
	field := func(label, attrs string) string {
		return fmt.Sprintf(`
    field {
      label = "%s"
      type  = "CONCEALED"
      %s
    }`, label, attrs)
	}
	sectionWith := func(label string, fields ...string) string {
		return fmt.Sprintf(`
  section {
    label = "%s"%s
  }`, label, strings.Join(fields, ""))
	}
	section := sectionWith("Secrets", field("api key", recipe(32)))
	fittingField := field("api key", fmt.Sprintf("value = %q", sectionSecret))
	fittingSection := sectionWith("Secrets", fittingField)

	passwordPath := tfjsonpath.New("password")
	sectionValuePath := tfjsonpath.New("section").AtSliceIndex(0).AtMapKey("field").AtSliceIndex(0).AtMapKey("value")

	testCases := map[string]struct {
		item          *model.Item
		before, after string
		imported      bool
		updated       string // config applied after import, before the final step
		valuePath     tfjsonpath.Path
		kept          string // empty means the value must be regenerated
	}{
		"import with same recipe keeps password": {
			item: loginItem, before: recipe(32), after: recipe(32), imported: true,
			valuePath: passwordPath, kept: password,
		},
		"import with same recipe keeps section field": {
			item: itemWithSection, before: section, after: section, imported: true,
			valuePath: sectionValuePath, kept: sectionSecret,
		},
		"import with changed recipe regenerates": {
			item: loginItem, before: recipe(32), after: recipe(20), imported: true,
			valuePath: passwordPath,
		},
		"import then update clears flag, fitting recipe added regenerates": {
			item: loginItem, before: fmt.Sprintf("password = %q", password), imported: true,
			updated: fmt.Sprintf("password = %q\n  note_value = \"updated\"", password), after: recipe(32),
			valuePath: passwordPath,
		},
		"existing item with fitting recipe added regenerates": {
			item: loginItem, before: fmt.Sprintf("password = %q", password), after: recipe(32),
			valuePath: passwordPath,
		},
		// Sections and fields are matched by list index, so the new field's state is the fitting "api key".
		"import with recipe field inserted before fitting field regenerates": {
			item: itemWithSection, before: fittingSection, imported: true,
			after:     sectionWith("Secrets", field("new", recipe(32)), fittingField),
			valuePath: sectionValuePath,
		},
		"import with recipe section inserted before fitting section regenerates": {
			item: itemWithSection, before: fittingSection, imported: true,
			after:     sectionWith("Other", field("api key", recipe(32))) + fittingSection,
			valuePath: sectionValuePath,
		},
	}

	for name, tc := range testCases {
		t.Run(name, func(t *testing.T) {
			item := tc.item
			srv := setupTestServer(item, model.Vault{ID: item.VaultID, Name: "VaultName"}, t)
			defer srv.Close()

			provider := testAccProviderConfig(srv.URL)
			res := func(body string) string {
				return provider + fmt.Sprintf(`
resource "onepassword_item" "example" {
  vault    = "%s"
  title    = "%s"
  category = "login"
  username = "test_user"
  url      = "some_url.com"
  %s
}
`, item.VaultID, item.Title, body)
			}

			steps := []resource.TestStep{{Config: res(tc.before)}}
			if tc.imported {
				steps = append(steps,
					// Equivalent of `terraform state rm`.
					resource.TestStep{Config: provider + `
removed {
  from = onepassword_item.example
  lifecycle {
    destroy = false
  }
}
`},
					resource.TestStep{
						Config:             res(tc.before),
						ResourceName:       "onepassword_item.example",
						ImportState:        true,
						ImportStatePersist: true,
						ImportStateId:      itemTerraformID(item),
					},
				)
			}
			if tc.updated != "" {
				steps = append(steps, resource.TestStep{Config: res(tc.updated)})
			}

			planCheck := plancheck.ExpectUnknownValue("onepassword_item.example", tc.valuePath)
			var stateChecks []statecheck.StateCheck
			if tc.kept != "" {
				planCheck = plancheck.ExpectKnownValue("onepassword_item.example", tc.valuePath, knownvalue.StringExact(tc.kept))
				stateChecks = []statecheck.StateCheck{
					statecheck.ExpectKnownValue("onepassword_item.example", tc.valuePath, knownvalue.StringExact(tc.kept)),
				}
			}
			steps = append(steps, resource.TestStep{
				Config: res(tc.after),
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{planCheck},
				},
				ConfigStateChecks: stateChecks,
			})

			resource.UnitTest(t, resource.TestCase{
				ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
				Steps:                    steps,
			})
		})
	}
}
