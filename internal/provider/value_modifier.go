// sameLabels reports whether a section field and its section have the same labels in state and plan.
// Both are matched by list index, so an inserted section or field would otherwise get a neighbour's value.
func sameLabels(ctx context.Context, req planmodifier.StringRequest) bool {
	field := req.Path.ParentPath()
	if len(field.Steps()) == 0 {
		return true
	}
	section := field.ParentPath().ParentPath()
	for _, p := range []path.Path{field.AtName("label"), section.AtName("label")} {
		var stateLabel, planLabel types.String
		if req.State.GetAttribute(ctx, p, &stateLabel).HasError() ||
			req.Plan.GetAttribute(ctx, p, &planLabel).HasError() ||
			!stateLabel.Equal(planLabel) {
			return false
		}
	}
	return true
}

var (
	digitsRegexp  = regexp.MustCompile("[0-9]")
	symbolsRegexp = regexp.MustCompile("[^a-zA-Z0-9]")
)

// valueFitsRecipe reports whether value could have been generated by recipe.
// The 1Password generator includes every enabled character set, so presence must match exactly.
func valueFitsRecipe(value string, recipe PasswordRecipeModel) bool {
	if recipe.Length.IsUnknown() || recipe.Digits.IsUnknown() || recipe.Symbols.IsUnknown() {
		return false
	}
	return int64(utf8.RuneCountInString(value)) == recipe.Length.ValueInt64() &&
		digitsRegexp.MatchString(value) == recipe.Digits.ValueBool() &&
		symbolsRegexp.MatchString(value) == recipe.Symbols.ValueBool()
}
